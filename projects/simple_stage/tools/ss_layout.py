"""SIMPLE STAGE slot and row layout: the one source of every count the graph and the Surface share.

    python tools/ss_layout.py           # writes modules/_shared/ss_layout.hlsli and scripts/show/rig_layout.luau
    python tools/ss_layout.py --check   # also reports manifest literals that disagree with the layout

Each fixture family has a fixed slot range with room for guests (a fixture added in the Fixture Rig takes a free
slot of its role), so stored looks survive every rig change. Program rows follow PHAGE's layered scheme:
  rows 0..SLOTS-1               each slot's base layer: MOVE (movers), TUBE (strobes), PIXELS (pixel runs)
  rows BEAM0..BEAM0+MOVERS-1    the movers' BEAM, slot + BEAM0
  rows LAYER2..ROWS-1           the second layer, slot + LAYER2: HALO (movers), PLATES (strobes), CHASE (runs)
`--check` never rewrites a manifest: a scripted manifest edit once blanked a renderer by dropping a line.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

MOVER0, MOVERS = 0, 32           # Halo Beams
STROBE0, STROBES = 32, 16        # Linear Strobes
BAR0, BARS = 48, 16              # pixel runs (a run is one or more battens end to end)
SLOTS = 64
AXIS0, AXES = SLOTS, 0           # no kinetic axes: the trusses are fixed
BEAM0 = SLOTS
LAYER2 = SLOTS + MOVERS
ROWS = LAYER2 + SLOTS
BAR_SEGS = 4                     # straight pieces per run
OPT_PER = 25                     # Optics records per mover: the beam, then 24 halo cells
OPT_STROBE0 = MOVERS * OPT_PER
OPT_COUNT = OPT_STROBE0 + STROBES
PARTITION = 32                   # slots per packed bank (rig_codec), so each text stays under 4096 characters
BANKS = (SLOTS + PARTITION - 1) // PARTITION
# Structure: truss members (expanded into tubes, TUBES_PER slots each), then oriented solids.
MEMBERS = 32
TUBES_PER = 96
TUBE_COUNT = MEMBERS * TUBES_PER
SOLID_COUNT = 64
STRUCTURE_COUNT = TUBE_COUNT + SOLID_COUNT

assert MOVER0 + MOVERS == STROBE0 and STROBE0 + STROBES == BAR0 and BAR0 + BARS == SLOTS
assert SLOTS % 16 == 0 and SLOTS <= 256, "presence words are 16 slots each, 16 words at most"

DEFINES = [
    ("SLOTS", SLOTS, "fixture slots"), ("ROWS", ROWS, "program rows"),
    ("BEAM0", BEAM0, "BEAM row of mover slot s: s + SS_BEAM0"),
    ("LAYER2", LAYER2, "HALO / PLATES / CHASE row of slot s: s + SS_LAYER2"),
    ("MOVER0", MOVER0, ""), ("MOVERS", MOVERS, ""), ("STROBE0", STROBE0, ""), ("STROBES", STROBES, ""),
    ("BAR0", BAR0, ""), ("BARS", BARS, ""), ("AXIS0", AXIS0, "no axes: one past the last slot"), ("AXES", AXES, ""),
    ("BAR_SEGS", BAR_SEGS, "straight pieces per pixel run"),
    ("OPT_PER", OPT_PER, "Optics records per mover"), ("OPT_STROBE0", OPT_STROBE0, "first strobe record"),
    ("OPT_COUNT", OPT_COUNT, ""),
    ("MEMBERS", MEMBERS, "truss members"), ("TUBES_PER", TUBES_PER, ""), ("TUBE_COUNT", TUBE_COUNT, ""),
    ("SOLID_COUNT", SOLID_COUNT, ""), ("STRUCTURE_COUNT", STRUCTURE_COUNT, "tubes, then solids"),
    ("PRESENCE_WORDS", SLOTS // 16, "rig_word0.. control outputs"),
]


def hlsl():
    out = ["// Generated by tools/ss_layout.py; edit the generator, not this file.",
           "// Every count the graph shares. tools/ss_layout.py --check lists manifest literals that disagree.",
           "#ifndef SS_LAYOUT_HLSLI", "#define SS_LAYOUT_HLSLI"]
    for name, v, note in DEFINES:
        out.append(f"#define SS_{name} {v}" + (f"   // {note}" if note else ""))
    out += ["#endif", ""]
    return "\n".join(out)


def luau():
    out = ["--!strict", "-- Generated by tools/ss_layout.py; edit the generator, not this file.",
           "-- The slot and row layout the programmer shares with the graph (modules/_shared/ss_layout.hlsli).",
           "return {"]
    for name, v, _ in DEFINES:
        out.append(f"    {name}={v},")
    out += [f"    PARTITION={PARTITION},", f"    BANKS={BANKS},", "}", ""]
    return "\n".join(out)


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != text:
        path.write_text(text, encoding="utf-8", newline="\n")
        return True
    return False


# (manifest, regex with one group, expected value): literals a Module manifest cannot take from a define.
CHECKS = [
    ("SS_Lighting", r"name: optics, structured: true, element_size: 80, element_count: (\d+)", OPT_COUNT),
    ("SS_Lighting", r"name: poses, structured: true, element_size: 64, element_count: (\d+)", MOVERS),
    ("SS_Lighting", r"name: rigmounts, structured: true, element_size: 80, element_count: (\d+)", SLOTS),
    ("SS_Lighting", r"name: rigslots, structured: true, element_size: 32, element_count: (\d+)", SLOTS),
    ("SS_Lighting", r"name: rigmap, structured: true, element_size: 4, element_count: (\d+)", SLOTS + 8),
    ("SS_Lighting", r"name: selection, structured: true, element_size: 16, element_count: (\d+)", 4 + SLOTS + SLOTS // 16),
    ("SS_Lighting", r"- name: optics\n    shader: optics.hlsl\n    target: cs_5_0\n    dispatch: \[(\d+), 1, 1\]",
     (OPT_COUNT + 63) // 64),
    ("SS_Lighting", r"- name: motors\n    shader: motors.hlsl\n    target: cs_5_0\n    dispatch: \[(\d+), 1, 1\]",
     (MOVERS + 63) // 64),
    ("SS_Program", r"name: program, structured: true, element_size: 96, element_count: (\d+)", ROWS),
    ("SS_Stage", r"name: structure, structured: true, element_size: 64, element_count: (\d+)", STRUCTURE_COUNT),
    ("SS_Renderer", r"name: poses, structured: true, element_size: 64, element_count: (\d+)", MOVERS),
]


def check() -> int:
    bad = 0
    for module, pattern, want in CHECKS:
        path = ROOT / "modules" / module / "manifest.yaml"
        if not path.exists():
            print(f"  skip {module}: no manifest yet")
            continue
        m = re.search(pattern, path.read_text(encoding="utf-8"))
        if not m:
            print(f"  MISSING {module}: {pattern[:70]}")
            bad += 1
        elif int(m.group(1)) != want:
            print(f"  DRIFT {module}: {m.group(0).splitlines()[0][:70]}... is {m.group(1)}, layout says {want}")
            bad += 1
    # A shader that redefines a layout name, or names one of the layout's sizes as a slot-range literal, outlives the
    # layout silently: the DMX encoder kept PHAGE's strobe range (128 / 3200) and sent every strobe dark.
    names = {f"SS_{n}" for n, _, _ in DEFINES} | {"SS_MOVER_SLOTS", "SS_STROBE_SLOT0", "SS_STROBE_SLOTS", "BAR_PIECES"}
    for path in sorted((ROOT / "modules").rglob("*.hlsl*")):
        if path.name in ("ss_layout.hlsli",) or "generated" in path.name:
            continue
        for n, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            m = re.match(r"\s*#define\s+(\w+)\s+\(?(\d+)u?\b", line)
            if m and m.group(1) in names:
                print(f"  LITERAL {path.relative_to(ROOT)}:{n}: {line.strip()[:80]}")
                bad += 1
    print("layout check: " + ("ok" if bad == 0 else f"{bad} literal(s) disagree"))
    return bad


if __name__ == "__main__":
    changed = [write(ROOT / "modules/_shared/ss_layout.hlsli", hlsl()), write(ROOT / "scripts/show/rig_layout.luau", luau())]
    print(f"layout: {SLOTS} slots, {ROWS} rows, {BANKS} banks ({sum(changed)} file(s) rewritten)")
    if "--check" in sys.argv:
        sys.exit(1 if check() else 0)
